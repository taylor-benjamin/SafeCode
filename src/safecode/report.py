"""Render a ScanResult as a Markdown report for PR comments and the job summary.

Much of the text in a report comes from the scanned repository (file names)
or third parties (advisory summaries, extra Semgrep rules). All of it goes
through _text() or _code() before being placed in Markdown, so that a file
named "[click me](https://evil.example)" shows up as literal text, not a link.
"""

from __future__ import annotations

import re

from safecode import __version__
from safecode.mapping import NIST_SSDF, OWASP, standards_for_rule
from safecode.rules import Rule
from safecode.scanners.semgrep import EXTRA_RULE_ID
from safecode.schema import CheckStatus, Finding, ScanResult, Severity, StandardRef, ToolStatus

SEVERITY_ICON = {
    Severity.CRITICAL: "🔴",
    Severity.HIGH: "🟠",
    Severity.MEDIUM: "🟡",
    Severity.LOW: "🔵",
    Severity.INFO: "⚪",
}
CHECK_ICON = {
    CheckStatus.PASSED: "✅",
    CheckStatus.FAILED: "❌",
    CheckStatus.SKIPPED: "⏭️",
    CheckStatus.ERROR: "⚠️",
}
TOOL_STATUS_TEXT = {
    ToolStatus.OK: "✅ ran",
    ToolStatus.NOT_INSTALLED: "⏭️ not installed",
    ToolStatus.TIMEOUT: "⚠️ timed out",
    ToolStatus.ERROR: "⚠️ error",
    ToolStatus.SKIPPED: "⏭️ skipped",
}
# Critical and high findings are always visible; the rest sit in collapsed sections.
_EXPANDED = {Severity.CRITICAL, Severity.HIGH}

DEFAULT_MAX_FINDINGS = 60


def render(result: ScanResult, rules: dict[str, Rule], *, repo_name: str = "",
           max_findings: int = DEFAULT_MAX_FINDINGS) -> str:
    """Build the full Markdown report."""
    heading = "## 🛡️ SAFECODE security report"
    if repo_name:
        heading += f" for {_code(repo_name)}"

    sections = [
        heading,
        _summary_line(result),
        _checklist_table(result, rules),
        _findings_section(result, rules, max_findings),
        _tools_table(result),
        _notes(result),
        f"<sub>Generated by SAFECODE {__version__}. Findings map to OWASP Top 10 2025, CWE, and NIST SSDF (SP 800-218).</sub>",
    ]
    return "\n\n".join(section for section in sections if section) + "\n"


def _summary_line(result: ScanResult) -> str:
    counts = result.counts_by_severity()
    total = sum(counts.values())
    parts = " · ".join(f"{SEVERITY_ICON[sev]} {n} {sev.value}" for sev, n in counts.items())
    noun = "finding" if total == 1 else "findings"
    return f"**{total} {noun}**: {parts}"


def _checklist_table(result: ScanResult, rules: dict[str, Rule]) -> str:
    if not result.checks:
        return ""
    rows = ["### Checklist", "", "| | Rule | Result | Standards |", "|---|---|---|---|"]
    for check in result.checks:
        rule = rules.get(check.rule_id)
        name = rule.name if rule else check.rule_id
        standards = " · ".join(_short_id(ref) for ref in standards_for_rule(rule)) if rule else ""
        rows.append(
            f"| {CHECK_ICON[check.status]} | **{check.rule_id}** {_text(name)} | {_text(check.summary)} | {standards} |"
        )
    return "\n".join(rows)


def _findings_section(result: ScanResult, rules: dict[str, Rule], max_findings: int) -> str:
    findings = result.sorted_findings()
    if not findings:
        return "### Findings\n\nNo findings. Nice work! 🎉"

    shown, hidden = findings[:max_findings], len(findings) - max_findings
    blocks = ["### Findings"]
    for severity in Severity:
        group = [f for f in shown if f.severity is severity]
        if not group:
            continue
        title = f"{SEVERITY_ICON[severity]} {severity.value.capitalize()} ({len(group)})"
        body = "\n\n".join(_finding_block(f, rules) for f in group)
        if severity in _EXPANDED:
            blocks.append(f"#### {title}\n\n{body}")
        else:
            blocks.append(f"<details>\n<summary><b>{title}</b></summary>\n\n{body}\n\n</details>")
    if hidden > 0:
        blocks.append(f"*…and {hidden} more finding(s) not shown here. See the job summary for the full list.*")
    return "\n\n".join(blocks)


def _finding_block(finding: Finding, rules: dict[str, Rule]) -> str:
    """One finding: headline, location + standards, what was found, why, and fix."""
    where = _code(str(finding.location)) if finding.location else "repository-wide"
    rule_label = "extra Semgrep rule" if finding.rule_id == EXTRA_RULE_ID else finding.rule_id
    meta = " · ".join([where, rule_label, *(_link(ref) for ref in finding.standards)])

    lines = [f"**{_text(finding.title)}**", meta, "", f"> {_prose(finding.message)}", ""]
    if finding.why_it_matters:
        lines.append(f"- **Why it matters:** {_prose(finding.why_it_matters)}")
    if finding.fix:
        lines.append(f"- **Fix:** {_prose(finding.fix)}")
    refs = [r for r in finding.references if _is_safe_url(r)]
    if refs:
        lines.append("- **Learn more:** " + ", ".join(f"<{r}>" for r in refs))
    return "\n".join(lines)


def _tools_table(result: ScanResult) -> str:
    if not result.tools:
        return ""
    rows = ["<details>", "<summary>Scanners</summary>", "",
            "| Scanner | Version | Status | Time | Details |", "|---|---|---|---|---|"]
    for tool in result.tools:
        rows.append(
            f"| {tool.name} | {_text(tool.version) or '?'} | {TOOL_STATUS_TEXT[tool.status]} "
            f"| {tool.duration_s:.1f}s | {_text(tool.detail)} |"
        )
    rows += ["", "</details>"]
    return "\n".join(rows)


def _notes(result: ScanResult) -> str:
    if not result.notes:
        return ""
    return "**Notes**\n\n" + "\n".join(f"- ℹ️ {_text(note)}" for note in result.notes)


# --- Markdown safety helpers -------------------------------------------------

# Characters that start Markdown/HTML constructs. Parentheses don't need
# escaping once "[" and "]" are, because a link needs both.
_MD_SPECIAL = re.compile(r"([\\`*_{}\[\]<>|#~])")


def _text(value: str) -> str:
    """Untrusted text, flattened to one line and with Markdown syntax escaped."""
    return _MD_SPECIAL.sub(r"\\\1", " ".join(str(value).split()))


def _prose(value: str) -> str:
    """Untrusted text that may use `backticks` for inline code.

    Code spans are kept (they can't carry links or HTML) and everything
    between them is escaped like _text(). An unmatched trailing backtick is dropped.
    """
    parts = str(value).split("`")
    out = []
    for index, part in enumerate(parts):
        if index % 2 == 1 and index < len(parts) - 1 and part.strip():
            out.append(_code(part))
        elif part.strip():
            # _text() trims the edges; keep one space where the original had whitespace.
            lead = " " if part[0].isspace() else ""
            trail = " " if part[-1].isspace() else ""
            out.append(f"{lead}{_text(part)}{trail}")
        elif part:
            out.append(" ")
    return re.sub(r" {2,}", " ", "".join(out)).strip()


def _code(value: str) -> str:
    """Untrusted text shown as inline code. Backticks are removed so it can't break out."""
    return "`" + " ".join(str(value).replace("`", "'").split()) + "`"


def _short_id(ref: StandardRef) -> str:
    return f"SSDF {ref.id}" if ref.framework == NIST_SSDF else ref.id


def _link(ref: StandardRef) -> str:
    """A standard as a link, with its name as hover text. Standard URLs are built by mapping.py."""
    label = f"OWASP {ref.id}" if ref.framework == OWASP else _short_id(ref)
    if not ref.url:
        return label
    title = f' "{ref.name.replace(chr(34), "")}"' if ref.name else ""
    return f"[{label}]({ref.url}{title})"


def _is_safe_url(url: str) -> bool:
    """Only plain https links from third-party metadata are shown."""
    return bool(re.fullmatch(r"https://[^\s<>()\"'`]+", url))
